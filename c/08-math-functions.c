#include <stdio.h>
#include <math.h>
#include <stdlib.h>

int main(){
  
  int x = 9;

  // square root
    x = sqrt(x);

  // power
    x = pow(x, 3);

  // round
    x = roundf(x);

  // ceiling (round up)
    x = ceil(x);

  // floor (round down)
    x = floor(x);

  // absolute value
    x = abs(x);

  // log
    x = log(x);

  // sine function
    x = sin(x);

  // cosine function
    x = cos(x);

  // tangent function
    x = tan(x);

  return 0;
}
